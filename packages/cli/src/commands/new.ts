export const buildProjectDocument = (
  options: NewProjectOptions,
  manifest: EngineVersionsManifest,
  now: number = Date.now(),
  id: string = `project_${randomUUID()}`,
): PixlProjectShape => {
  const sceneId = 'main';
  const slug = slugify(options.name);
  const runtime = buildRuntime(options.kind);
  const runtimeDeps = manifest.runtimes[runtime.primary]?.dependencies ?? {};

  return {
    format: PIXL_PROJECT_FORMAT,
    version: PIXL_PROJECT_VERSION,
    id,
    slug,
    name: options.name,
    createdAt: now,
    savedAt: now,
    activeSceneId: sceneId,
    scenes: [buildSceneFor(options.kind, sceneId)],
    assets: { root: 'Assets', folders: [...DEFAULT_FOLDERS], entries: [] },
    engine: {
      name: 'PixlPlayground',
      version: manifest.engine.version,
      schemaVersion: manifest.schemaVersion,
      runtimeManifest: {
        runtime: runtime.primary,
        dependencies: { ...runtimeDeps },
      },
    },
    runtime,
    editor: {
      mode: options.kind,
      transformSpace: 'world',
      snapEnabled: false,
      snapTranslate: 1,
      snapRotate: 15,
      snapScale: 0.25,
      selectedSceneId: sceneId,
      layoutPreset: 'default',
    },
    game: {
      templateId: null,
      script: '// Pixlland game script\n// Escreva sua logica aqui.\n',
    },
  };
};

const scaffoldFolder = async (root: string, folder: string): Promise<void> => {
  const folderPath = join(root, folder);
  await mkdir(folderPath, { recursive: true });
  await writeFile(join(folderPath, '.gitkeep'), '', 'utf8');
};

export const runNew = async (options: NewProjectOptions): Promise<NewProjectResult> => {
  const absoluteDir = resolve(process.cwd(), options.targetDir);
  if ((await exists(absoluteDir)) && !options.force) {
    throw new Error(`Diretorio "${absoluteDir}" ja existe. Use --force pra sobrescrever.`);
  }

  const { manifest } = await findEngineManifest(process.cwd(), { startKind: 'directory' });

  await mkdir(absoluteDir, { recursive: true });
  await Promise.all(DEFAULT_FOLDERS.map((folder) => scaffoldFolder(absoluteDir, folder)));

  const projectDoc = buildProjectDocument(options, manifest);
  const projectFile = join(absoluteDir, 'project.pixlproject.json');
  await Promise.all([
    writeFile(projectFile, `${JSON.stringify(projectDoc, null, 2)}\n`, 'utf8'),
    writeFile(join(absoluteDir, '.gitignore'), PROJECT_GITIGNORE, 'utf8'),
  ]);

  return {
    projectDir: absoluteDir,
    projectFile,
    kind: options.kind,
    runtime: projectDoc.runtime!.primary as PixlRuntimeKind,
  };
};

