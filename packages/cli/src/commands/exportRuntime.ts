/**
 * Returns the runtime entry path relative to a project doc, OR null if the
 * project doesn't declare one. Doesn't touch the filesystem — the I/O wrapper
 * checks existence and tries the `runtime/` fallback.
 */
export const extractRuntimeEntry = (project: PixlProjectShape): string | null => {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const game = project.game as any;
  const fromSource = game?.source?.runtimeFile;
  if (typeof fromSource === 'string' && fromSource.length > 0) return fromSource;
  return null;
};

export const exportProjectToRuntime = (
  project: PixlProjectShape,
  absoluteRuntimePath: string,
  options: ExportRuntimeOptions = {},
): ExportRuntimeResult => {
  if (project.format !== 'pixlplayground-project') {
    throw new Error(
      `exportProjectToRuntime: unexpected project format "${project.format}". Expected "pixlplayground-project".`,
    );
  }

  const title = options.title ?? project.name;
  const pageBackground = options.pageBackground ?? '#000';

  const indexHtml = buildIndexHtml(title, pageBackground);
  const entryJsSource = buildEntryJsSource(absoluteRuntimePath);

  const manifest: ExportRuntimeManifest = {
    format: EXPORT_RUNTIME_FORMAT,
    formatVersion: EXPORT_RUNTIME_FORMAT_VERSION,
    exportedAt: options.exportedAt ?? 0,
    projectId: project.id,
    projectName: project.name,
    runtimeEntry: absoluteRuntimePath,
    runtime: 'standalone-game',
  };

  return { indexHtml, entryJsSource, manifest };
};

