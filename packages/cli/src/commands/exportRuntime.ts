// pixl-engine export-runtime — emits a standalone web bundle for the
// project's GAME runtime (the JS file referenced by p.game.source.runtimeFile),
// not the engine's editorial snapshot.
//
// Distinct from export-three:
//   - export-three   bundles @pixlland/three-runtime + the project doc; the
//                    result is a viewer of the editor's view of the scene.
//   - export-runtime bundles the game's own main.js (which has its own
//                    Three.js setup, input loop, physics, HUD). The result
//                    is the game, playable.
//
// Typical project shape (Harvest Rush 3D):
//   <projectDir>/
//     project.pixlproject.json       (engine snapshot — not used here)
//     runtime/src/main.js            (the game)
//     runtime/src/styles.css         (game UI)
//     assets/vendor/...              (binaries the game fetches)
//     levels/...                     (level/save data, optional)
//
// p.game.source.runtimeFile points at the entry relative to either projectDir
// or projectDir/runtime/. The command resolves whichever exists. The Vite
// build then bundles that file + transitive imports + CSS, and the runner
// copies sibling asset dirs (assets/, levels/) verbatim into the output.

import { mkdir, writeFile, readFile, copyFile, stat, rm, mkdtemp, readdir, cp } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { PixlProjectShape } from '../schema.js';

// ---------------------------------------------------------------------------
// Public API (pure)
// ---------------------------------------------------------------------------

export const EXPORT_RUNTIME_FORMAT = 'pixlplayground-export-runtime' as const;
export const EXPORT_RUNTIME_FORMAT_VERSION = 1 as const;

export interface ExportRuntimeOptions {
  /** `<title>` text. Defaults to `project.name`. */
  title?: string;
  /** CSS background of the host page. Defaults to `#000`. */
  pageBackground?: string;
  /**
   * Deterministic timestamp for the manifest. Tests pin this; production
   * leaves it undefined and the runner stamps Date.now().
   */
  exportedAt?: number;
}

export interface ExportRuntimeManifest {
  format: typeof EXPORT_RUNTIME_FORMAT;
  formatVersion: typeof EXPORT_RUNTIME_FORMAT_VERSION;
  exportedAt: number;
  projectId: string;
  projectName: string;
  runtimeEntry: string;
  runtime: 'standalone-game';
}

export interface ExportRuntimeResult {
  indexHtml: string;
  /** Tiny bridge module: `import '<absolute-path-to-game-main.js>'`. Vite chases the import. */
  entryJsSource: string;
  manifest: ExportRuntimeManifest;
}

// ---------------------------------------------------------------------------
// Templates
// ---------------------------------------------------------------------------

const escapeHtml = (value: string): string =>
  value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

const buildIndexHtml = (title: string, pageBackground: string): string => {
  const safeTitle = escapeHtml(title);
  const safeBg = escapeHtml(pageBackground);
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    `<title>${safeTitle}</title>`,
    '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">',
    '<style>',
    `html,body{margin:0;padding:0;height:100%;background:${safeBg};overflow:hidden;font-family:system-ui,sans-serif;color:#eee}`,
    'canvas{display:block}',
    '#error{position:fixed;top:0;left:0;right:0;padding:12px 16px;background:#3a0a0a;color:#fca5a5;font:13px/1.4 ui-monospace,monospace;white-space:pre-wrap;display:none;z-index:9999}',
    '#error.show{display:block}',
    '</style>',
    '</head>',
    '<body>',
    '<div id="error"></div>',
    '<script type="module" src="./entry.js"></script>',
    '</body>',
    '</html>',
    '',
  ].join('\n');
};

const buildEntryJsSource = (absoluteRuntimePath: string): string => {
  // JSON.stringify gives us a quoted path with escapes; Vite resolves it via
  // its own absolute-path import handling (works on macOS, Linux, Windows).
  const ref = JSON.stringify(absoluteRuntimePath);
  return [
    '// Generated by pixl-engine export-runtime. Do not edit by hand.',
    '// This is a 3-line shim — the real game lives at the imported path.',
    'window.addEventListener(\'error\', (e) => {',
    '  const el = document.getElementById(\'error\');',
    '  if (el) { el.textContent = String(e.error?.stack ?? e.message ?? e); el.classList.add(\'show\'); }',
    '});',
    'window.addEventListener(\'unhandledrejection\', (e) => {',
    '  const el = document.getElementById(\'error\');',
    '  if (el) { el.textContent = String(e.reason?.stack ?? e.reason ?? e); el.classList.add(\'show\'); }',
    '});',
    `import ${ref};`,
    '',
  ].join('\n');
};

