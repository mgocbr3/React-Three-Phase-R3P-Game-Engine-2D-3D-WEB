export interface RunExportRuntimeOptions extends ExportRuntimeOptions {
  /**
   * Override runtimeFile lookup. Defaults to project.game.source.runtimeFile.
   * Useful when the project doc doesn't declare a runtime entry but you want
   * to bundle one anyway.
   */
  runtimeFile?: string;
  /**
   * Directories (relative to projectDir) to copy verbatim into the bundle.
   * Defaults to ['assets', 'levels']. Missing dirs are silently skipped.
   * The game's main.js fetches binaries from these subpaths.
   */
  assetDirs?: string[];
  /** Skip Vite bundling and emit raw entry files. Tests use this. */
  skipBundle?: boolean;
  /** Pass-through to vite.build({ build: { sourcemap } }). */
  sourcemap?: boolean;
  /** Pass-through to vite.build({ build: { minify: false } }) when set to false. */
  minify?: boolean;
  /** Override CLI package dir for module resolution. Tests use this. */
  cliPackageDir?: string;
}

export interface RunExportRuntimeResult {
  outDir: string;
  fileCount: number;
  /** Absolute path of the resolved runtime entry (`runtime/src/main.js`). */
  runtimeEntry: string;
  /** Total bytes of bundle JS chunks under `<outDir>/assets/`. */
  bundleSizeBytes: number;
  /** Subdir copies that succeeded (`assets/`, `levels/`, etc.). */
  copiedDirs: string[];
  /** Subdirs that were requested but not found on disk. */
  missingDirs: string[];
}

const fileExists = async (path: string): Promise<boolean> => {
  try {
    const s = await stat(path);
    return s.isFile();
  } catch {
    return false;
  }
};

const dirExists = async (path: string): Promise<boolean> => {
  try {
    const s = await stat(path);
    return s.isDirectory();
  } catch {
    return false;
  }
};

const defaultCliPackageDir = (): string => {
  const here = fileURLToPath(import.meta.url);
  return resolve(dirname(here), '..', '..');
};

// Recursively sum bytes of every .js file under `dir`.
const sumJsBytesRecursive = async (dir: string): Promise<number> => {
  let total = 0;
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return 0;
  }
  for (const entry of entries) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      total += await sumJsBytesRecursive(full);
    } else if (entry.isFile() && entry.name.endsWith('.js')) {
      total += (await stat(full)).size;
    }
  }
  return total;
};

/**
 * Locate the runtime entry on disk. Tries `<projectDir>/<runtimeFile>` first;
 * falls back to `<projectDir>/runtime/<runtimeFile>` (the Pixlland convention
 * where game code lives under a `runtime/` subdir alongside the project doc).
 */
const resolveRuntimeFile = async (
  projectDir: string,
  runtimeFile: string,
): Promise<string> => {
  const direct = resolve(projectDir, runtimeFile);
  if (await fileExists(direct)) return direct;
  const underRuntimeDir = resolve(projectDir, 'runtime', runtimeFile);
  if (await fileExists(underRuntimeDir)) return underRuntimeDir;
  throw new Error(
    `export-runtime: could not locate runtime entry "${runtimeFile}". ` +
      `Tried "${direct}" and "${underRuntimeDir}".`,
  );
};

export const runExportRuntime = async (
  projectPath: string,
  outDir: string,
  options: RunExportRuntimeOptions = {},
): Promise<RunExportRuntimeResult> => {
  const absProject = resolve(process.cwd(), projectPath);
  const absOut = resolve(process.cwd(), outDir);
  const projectDir = dirname(absProject);

  const raw = await readFile(absProject, 'utf8');
  const project = JSON.parse(raw) as PixlProjectShape;

  const runtimeFile = options.runtimeFile ?? extractRuntimeEntry(project);
  if (!runtimeFile) {
    throw new Error(
      'export-runtime: project does not declare game.source.runtimeFile and no --runtime-file was passed.',
    );
  }
  const resolvedRuntime = await resolveRuntimeFile(projectDir, runtimeFile);

  const exportedAt = options.exportedAt ?? Date.now();
  const result = exportProjectToRuntime(project, resolvedRuntime, {
    ...options,
    exportedAt,
  });

  await mkdir(absOut, { recursive: true });
  await writeFile(
    resolve(absOut, 'manifest.json'),
    `${JSON.stringify(result.manifest, null, 2)}\n`,
    'utf8',
  );

  // Copy asset sibling dirs (assets/, levels/, ...) into the bundle. The
  // game's main.js fetches binaries via relative paths like `./assets/...`.
  const requestedDirs = options.assetDirs ?? ['assets', 'levels'];
  const copiedDirs: string[] = [];
  const missingDirs: string[] = [];
  for (const sub of requestedDirs) {
    const src = resolve(projectDir, sub);
    if (await dirExists(src)) {
      await cp(src, resolve(absOut, sub), { recursive: true });
      copiedDirs.push(sub);
    } else {
      missingDirs.push(sub);
    }
  }

  if (options.skipBundle) {
    await writeFile(resolve(absOut, 'index.html'), result.indexHtml, 'utf8');
    await writeFile(resolve(absOut, 'entry.js'), result.entryJsSource, 'utf8');
    const bundleSizeBytes = Buffer.byteLength(result.entryJsSource, 'utf8');
    const fileCount = 3 + copiedDirs.length; // index.html + entry.js + manifest.json + copied dirs (counted as 1 each)
    return {
      outDir: absOut,
      fileCount,
      runtimeEntry: resolvedRuntime,
      bundleSizeBytes,
      copiedDirs,
      missingDirs,
    };
  }

  const cliPackageDir = options.cliPackageDir ?? defaultCliPackageDir();
  const tmpBase = join(cliPackageDir, '.tmp');
  await mkdir(tmpBase, { recursive: true });
  const tmpRoot = await mkdtemp(join(tmpBase, 'export-runtime-root-'));

  let bundleSizeBytes = 0;
  try {
    await writeFile(resolve(tmpRoot, 'index.html'), result.indexHtml, 'utf8');
    await writeFile(resolve(tmpRoot, 'entry.js'), result.entryJsSource, 'utf8');

    const vite = await import('vite');
    await vite.build({
      configFile: false,
      root: tmpRoot,
      logLevel: 'error',
      base: './',
      // resolvedRuntime sits OUTSIDE tmpRoot — explicitly let Vite read its
      // directory and the project's runtime tree.
      server: { fs: { allow: [tmpRoot, dirname(resolvedRuntime), projectDir] } },
      build: {
        outDir: absOut,
        emptyOutDir: false,
        target: 'es2022',
        sourcemap: options.sourcemap === true,
        ...(options.minify === false ? { minify: false as const } : {}),
      },
    });
    bundleSizeBytes = await sumJsBytesRecursive(resolve(absOut, 'assets'));
  } finally {
    await rm(tmpRoot, { recursive: true, force: true });
  }

  // fileCount: 2 hand-written (manifest.json + index.html-from-Vite) +
  // Vite chunks + copied dirs.
  const fileCount = 2 + copiedDirs.length;

  return {
    outDir: absOut,
    fileCount,
    runtimeEntry: resolvedRuntime,
    bundleSizeBytes,
    copiedDirs,
    missingDirs,
  };
};

export const printExportRuntimeResult = (result: RunExportRuntimeResult): void => {
  // eslint-disable-next-line no-console
  console.log('pixl-engine export-runtime');
  console.log(`  out:          ${result.outDir}`);
  console.log(`  runtime:      ${result.runtimeEntry}`);
  console.log(`  files:        ${result.fileCount}`);
  console.log(`  bundle bytes: ${result.bundleSizeBytes.toLocaleString()}`);
  if (result.copiedDirs.length > 0) {
    console.log(`  copied dirs:  ${result.copiedDirs.join(', ')}`);
  }
  if (result.missingDirs.length > 0) {
    console.log(`  missing dirs: ${result.missingDirs.join(', ')}`);
  }
};
